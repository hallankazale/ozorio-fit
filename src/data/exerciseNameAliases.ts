function normalizedExerciseName(name: string): string {
  return name.toLowerCase().normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

const aliasLookup = new Map<string, string>();
for (const group of anatomicalGifAliases) {
  for (const alias of group.names) {
    const key = normalizedExerciseName(alias);
    if (aliasLookup.has(key) && aliasLookup.get(key) !== group.file) {
      throw new Error(`Alias de exercício conflitante: ${alias}`);
    }
    aliasLookup.set(key, group.file);
  }
}

/** Retorna caminho validado ou nulo, sem adivinhar um exercício diferente. */
export function anatomicalGifAlias(name: string): string | null {
  return aliasLookup.get(normalizedExerciseName(name)) ?? null;
}
